"""
Every pickle shipped in data_store/ loads cleanly on the locked dependency set.

The site build and the backtest unpickle these files. A version-skew warning on
load (sklearn's InconsistentVersionWarning, XGBoost's "serialized model
generated by an older version") means the library may rebuild the object
incorrectly, so it is an error here, not noise. The C21-era classifier pickle
carried sklearn/XGBoost class pickles and failed exactly this way.
"""
import pickle
import warnings

import numpy as np
import pandas as pd
import pytest

from joint_vol_calibration.tests.conftest import DATA_STORE

PICKLES = sorted(p for p in DATA_STORE.rglob("*.pkl") if "mc_cache" not in p.parts)


def _load_strict(path):
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        with open(path, "rb") as fh:
            return pickle.load(fh)


def test_there_are_shipped_pickles_to_check():
    names = {p.name for p in PICKLES}
    assert {"regime_classifier.pkl", "pdv_model.pkl", "full_results.pkl"} <= names


@pytest.mark.parametrize("path", PICKLES, ids=lambda p: str(p.relative_to(DATA_STORE)))
def test_pickle_loads_without_version_warnings(path):
    assert _load_strict(path) is not None


def test_classifier_predicts_without_version_warnings():
    from joint_vol_calibration.signals.regime_classifier import RegimeClassifier

    clf = _load_strict(DATA_STORE / "signals" / "regime_classifier.pkl")
    assert isinstance(clf, RegimeClassifier) and clf.model_ is not None
    X = pd.DataFrame(np.zeros((3, len(clf.feature_names_))), columns=clf.feature_names_)
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        proba = np.asarray(clf.predict_proba(X))
    assert proba.shape[0] == 3
    assert np.allclose(proba.sum(axis=1), 1.0)
