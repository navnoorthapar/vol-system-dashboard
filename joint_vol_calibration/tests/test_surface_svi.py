"""
Raw SVI per expiry (surface/svi.py): formulas, the SSVI -> raw SVI map,
Axel Vogt's butterfly-arbitrage example (Gatheral-Jacquier Example 3.1), and
constrained fits.
"""
import numpy as np

from joint_vol_calibration.surface import essvi as es
from joint_vol_calibration.surface import svi as sv

# GJ list (a, b, m, rho, sigma) = (-0.0410, 0.1331, 0.3586, 0.3060, 0.4153), t = 1;
# this module's order is (a, b, rho, m, sigma)
VOGT = (-0.0410, 0.1331, 0.3060, 0.3586, 0.4153)


def test_svi_derivatives_match_finite_differences():
    p = (0.01, 0.1, -0.4, 0.05, 0.2)
    k = np.linspace(-1.5, 1.0, 501)
    h = 1e-5
    w, w1, w2 = sv.svi_derivatives(k, *p)
    np.testing.assert_allclose(w1, (sv.svi_w(k + h, *p) - sv.svi_w(k - h, *p)) / (2 * h), atol=1e-8)
    np.testing.assert_allclose(w2, (sv.svi_w(k + h, *p) - 2 * w + sv.svi_w(k - h, *p)) / h ** 2,
                               atol=2e-4)


def test_ssvi_slice_maps_to_raw_svi_exactly():
    rng = np.random.default_rng(7)
    k = np.linspace(-2.0, 1.5, 701)
    for _ in range(50):
        th, ps, rh = rng.uniform(1e-3, 0.3), rng.uniform(0.02, 1.0), rng.uniform(-0.95, 0.95)
        np.testing.assert_allclose(sv.svi_w(k, *sv.ssvi_slice_to_raw(th, ps, rh)),
                                   es.essvi_w(k, th, ps, rh), rtol=1e-12, atol=1e-15)


def test_vogt_parameters_have_butterfly_arbitrage():
    """GJ Example 3.1 / Figure 1: g turns negative on the right of the money."""
    k = np.linspace(-1.5, 1.5, 3001)
    g = sv.svi_g(k, VOGT)
    assert g.min() < -0.03
    assert 0.6 < k[np.argmin(g)] < 1.1
    assert g[k < 0].min() > 0


K_QUOTES = np.linspace(-0.5, 0.3, 41)


def _quotes(params, T, k=K_QUOTES):
    return k, np.sqrt(sv.svi_w(k, *params) / T)


def test_fit_recovers_an_arbitrage_free_slice():
    T = 0.25
    true = (0.004, 0.08, -0.55, 0.02, 0.12)
    assert sv.svi_g(sv.SVI_GRID, true).min() > 0
    k, iv = _quotes(true, T)
    x0 = sv.ssvi_slice_to_raw(float(sv.svi_w(0.0, *true)), 0.15, -0.6)
    p, info = sv.fit_svi_slice(k, T, iv, np.full(len(k), 1e-3), x0)
    assert np.max(np.abs(np.sqrt(sv.svi_w(k, *p) / T) - iv)) < 1e-4
    assert info["g_min"] >= -1e-9 and info["max_constraint_violation"] < 1e-9


def test_fit_to_the_vogt_smile_is_forced_arbitrage_free():
    """Quotes generated by Vogt's slice: the constrained fit must not
    reproduce its negative density and so fits worse than the data."""
    T = 1.0
    k, iv = _quotes(VOGT, T, np.linspace(-0.8, 0.8, 81))
    x0 = sv.ssvi_slice_to_raw(float(sv.svi_w(0.0, *VOGT)), 0.2, 0.3)
    p, info = sv.fit_svi_slice(k, T, iv, np.full(len(k), 1e-3), x0)
    assert sv.svi_g(sv.SVI_GRID, p).min() >= -1e-8
    err = np.sqrt(sv.svi_w(k, *p) / T) - iv
    assert np.max(np.abs(err)) > 1e-4                       # cannot match an arbitrageable smile
    lee = max(p[1] * (1 + p[2]), p[1] * (1 - p[2]))
    assert lee <= 2.0


def test_surface_interpolates_total_variance_linearly_in_T():
    s = sv.SVISurface([sv.SVISlice("a", 0.1, (0.002, 0.05, -0.5, 0.0, 0.1)),
                       sv.SVISlice("b", 0.3, (0.006, 0.08, -0.5, 0.0, 0.1))])
    k = np.linspace(-0.5, 0.5, 11)
    np.testing.assert_allclose(s.w(k, 0.2), 0.5 * (s.slices[0].w(k) + s.slices[1].w(k)))
    np.testing.assert_allclose(s.w(k, 0.05), 0.5 * s.slices[0].w(k))
    d = sv.SVISurface.from_dict(s.to_dict())
    np.testing.assert_allclose(d.w(k, 0.2), s.w(k, 0.2), rtol=1e-15)
