"""
test_quintic_calibrator.py — QuinticCalibrator (C13, corrected in C22).

Most tests run against a SYNTHETIC market generated by the model itself
(monkeypatched database accessors, no network, no dependence on the shipped
DB): SPX and VIX option mids are the model's own premia, discounted at r, with
quotes on both sides of every strike. At the generating parameters every leg
of the loss must then vanish, which pins the target construction (put-call-
parity forwards, Black-76 on the forward, consistent discounting) and the
fact that every leg — including the VIX-forward leg — depends on the
parameters. Data-guard tests (same-session pinning, staleness, sufficiency)
and the committed 2026-03-24 pickle's provenance are covered at the end.
"""

import math
import pickle

import numpy as np
import pandas as pd
import pytest

from joint_vol_calibration.calibration import quintic_calibrator as qc
from joint_vol_calibration.config import VIX_INDEX_TENOR_DAYS
from joint_vol_calibration.models import quintic_ou as q

SPOT_DATE = "2026-03-24"
S0, R, QDIV = 6500.0, 0.04, 0.013
N_PATHS, SEED = 4000, 7
# A generating point inside the search box: (λx, λy, θ, a0, a1, a3, ε)
X_TRUE = np.array([40.0, 1.2, 0.85, 6.0, 9.0, 1.5, -0.7])
VIX_LEVELS = {"^VIX9D": 21.0, "^VIX": 20.0, "^VIX3M": 21.5, "^VIX6M": 22.5}
SPX_DAYS = [14, 30, 61, 91, 182, 365]
VIX_DAYS = [21, 49, 84, 147, 245]


def _fwd_var():
    tenors = np.array([VIX_INDEX_TENOR_DAYS[t] for t in VIX_LEVELS]) / 365.0
    return qc._bootstrap_fwd_var(tenors, np.array(list(VIX_LEVELS.values())) / 100.0)


def _quotes(snapshot, expiry, T, K, call_pv, put_pv, vendor_iv, volume=10.0):
    rows = []
    for right, pv in (("C", call_pv), ("P", put_pv)):
        rows.append(pd.DataFrame({
            "snapshot_date": snapshot, "expiry": expiry, "strike": K, "right": right,
            "bid": pv * 0.99, "ask": pv * 1.01, "mid_price": pv, "implied_vol": vendor_iv,
            "open_interest": 0, "volume": volume, "time_to_expiry": T}))
    return pd.concat(rows, ignore_index=True)


@pytest.fixture(scope="module")
def market():
    """Model-generated SPX and VIX chains on SPOT_DATE (computed once)."""
    p = qc.search_to_params(X_TRUE)
    fv = _fwd_var()
    # SPX: dense strikes, model smile from the same MC settings the calibrator uses
    Ts, Ks, Fs = [], [], []
    for d in SPX_DAYS:
        T = d / 365.0
        F = S0 * math.exp((R - QDIV) * T)
        K = np.arange(np.floor(0.55 * F / 25) * 25, 1.3 * F, 25.0)
        Ts.append(np.full(len(K), T)); Ks.append(K); Fs.append(np.full(len(K), F))
    Ts, Ks, Fs = map(np.concatenate, (Ts, Ks, Fs))
    iv = q.implied_vol_surface_forward_mc(Ts, Ks, Fs, p, fv, n_paths=N_PATHS, seed=SEED)
    D = np.exp(-R * Ts)
    spx = []
    for T in np.unique(Ts):
        m = Ts == T
        call = q.black76_price(Fs[m], Ks[m], T, iv[m], True, D[m])
        put = q.black76_price(Fs[m], Ks[m], T, iv[m], False, D[m])
        spx.append(_quotes(SPOT_DATE, f"exp{T:.4f}", T, Ks[m], call, put, 0.123))
    spx = pd.concat(spx, ignore_index=True)

    # VIX: model forward and premia on the calibrator's cubature
    vix, vix_fwd = [], {}
    for d in VIX_DAYS:
        T = d / 365.0
        nodes, w = q.vix_at_nodes(T, p, fv, qc._VIX_QUAD_OUTER, qc._VIX_QUAD_INNER)
        F = float(w @ nodes)
        K = np.arange(10.0, 3.2 * F, 1.0)
        call = np.maximum(nodes[:, None] - K[None, :], 0.0).T @ w
        put = np.maximum(K[None, :] - nodes[:, None], 0.0).T @ w
        Dv = math.exp(-R * T)
        vix_fwd[T] = F
        # vendor column deliberately inconsistent (BS on a fake spot): must be ignored
        vix.append(_quotes(SPOT_DATE, f"vexp{T:.4f}", T, K, Dv * call, Dv * put, 0.33))
    vix = pd.concat(vix, ignore_index=True)
    return {"params": p, "fv": fv, "spx": spx, "vix": vix, "vix_fwd": vix_fwd,
            "spx_iv": dict(zip(zip(Ts, Ks), iv))}


def _vts_long(rows):
    out = []
    for date, levels in rows.items():
        for t, v in levels.items():
            out.append({"date": pd.Timestamp(date), "ticker": t, "tenor_days": 0,
                        "close": v, "is_vvix": 0})
    return pd.DataFrame(out)


def _install(monkeypatch, market, spot_date=SPOT_DATE, spx_snapshot=SPOT_DATE,
             vix_snapshot=SPOT_DATE, vts=None, spx=None):
    spx_df = (market["spx"] if spx is None else spx).assign(snapshot_date=spx_snapshot)
    vix_df = market["vix"].assign(snapshot_date=vix_snapshot)
    vts = _vts_long({spot_date: VIX_LEVELS}) if vts is None else vts
    monkeypatch.setattr(qc.db, "get_spx_ohlcv", lambda as_of_date, start_date=None:
                        pd.DataFrame({"date": ["2026-03-20", spot_date], "close": [S0 * 1.01, S0]}))
    monkeypatch.setattr(qc.db, "get_tbill_rate", lambda as_of_date, fallback=0.045: R)
    monkeypatch.setattr(qc.db, "get_options_surface", lambda as_of_date, underlying:
                        spx_df.copy() if underlying == "SPX" else vix_df.copy())
    monkeypatch.setattr(qc.db, "get_vix_term_structure", lambda as_of_date, start_date=None:
                        vts.copy())


@pytest.fixture
def cal(monkeypatch, market):
    _install(monkeypatch, market)
    return qc.QuinticCalibrator(SPOT_DATE, n_paths=N_PATHS, seed=SEED)


# ── targets are rebuilt from prices, consistently discounted ─────────────────

class TestTargets:

    def test_parity_forwards_and_black76_targets_are_recovered(self, cal, market):
        s = cal.spx_surface
        F_true = S0 * np.exp((R - QDIV) * s["time_to_expiry"].values)
        np.testing.assert_allclose(s["forward"].values, F_true, rtol=1e-10)
        want = np.array([market["spx_iv"][(T, K)] for T, K in
                         zip(s["time_to_expiry"].values, s["strike"].values)])
        np.testing.assert_allclose(s["market_iv"].values, want, atol=1e-9)
        for row in cal.vix_forwards.itertuples():
            assert row.forward == pytest.approx(market["vix_fwd"][row.time_to_expiry], rel=1e-10)

    def test_vendor_iv_column_is_not_the_target(self, cal):
        # the vendor column (Black-Scholes on spot VIX in the real data) is kept
        # for reference only
        assert np.all(cal.vix_opts_surface["vendor_iv"] == 0.33)
        assert not np.allclose(cal.vix_opts_surface["market_iv"], 0.33)

    def test_spx_set_reaches_the_put_wing_and_is_otm(self, cal):
        s = cal.spx_surface
        assert s["time_to_expiry"].nunique() == len(SPX_DAYS)
        for T, g in s.groupby("time_to_expiry"):
            otm = np.where(g["right"] == "P", g["strike"] < g["forward"], g["strike"] >= g["forward"])
            assert otm.all()
            if T >= 30 / 365:
                assert (g["strike"] / g["forward"]).min() <= 0.90
            assert (g["strike"] / g["forward"]).max() > 1.0

    def test_vix_set_is_otm_liquid_and_on_the_moneyness_grid(self, cal, monkeypatch, market):
        v = cal.vix_opts_surface
        otm = np.where(v["right"] == "P", v["strike"] < v["forward"], v["strike"] >= v["forward"])
        assert otm.all()
        k = np.log(v["strike"] / v["forward"])
        assert k.min() >= qc._VIX_K_LO - 0.03 and k.max() <= qc._VIX_K_HI + 0.06
        assert v["time_to_expiry"].nunique() == len(VIX_DAYS)

        # A selected call that loses its volume (OI is 0 in the vendor feed),
        # or whose spread widens past 30% of mid, must drop out of the set.
        T0 = VIX_DAYS[1] / 365.0
        sel = v[(v["time_to_expiry"] == T0) & (v["right"] == "C")]
        K_bad = float(sel["strike"].iloc[len(sel) // 2])
        for mutate in ({"volume": 0.0}, {"ask_mult": 1.4}):
            vix = market["vix"].copy()
            bad = (vix["time_to_expiry"] == T0) & (vix["strike"] == K_bad) & (vix["right"] == "C")
            if "volume" in mutate:
                vix.loc[bad, "volume"] = mutate["volume"]
            else:
                vix.loc[bad, "ask"] = vix.loc[bad, "mid_price"] * mutate["ask_mult"]
            _install(monkeypatch, dict(market, vix=vix))
            v2 = qc.QuinticCalibrator(SPOT_DATE, n_paths=N_PATHS, seed=SEED).vix_opts_surface
            assert not ((v2["time_to_expiry"] == T0) & (v2["strike"] == K_bad)).any()


# ── the loss ─────────────────────────────────────────────────────────────────

class TestLoss:

    def test_every_leg_vanishes_at_the_generating_parameters(self, cal, market):
        ev = cal.evaluate(market["params"])
        assert np.max(np.abs(ev["spx_resid"])) < 1e-8
        assert np.max(np.abs(ev["vix_fwd_rel_resid"])) < 1e-12
        assert np.max(np.abs(ev["vix_resid"])) < 1e-8
        assert cal._loss(X_TRUE) < 1e-15

    @pytest.mark.parametrize("i, bump", [(0, 15.0), (1, 1.0), (2, -0.2), (3, 4.0), (4, 5.0),
                                         (5, 2.0)])
    def test_every_leg_depends_on_the_vol_parameters(self, cal, i, bump):
        # The pre-C22 'VIX futures' leg compared a ξ0-only quantity with the
        # indices and was identical for every parameter vector.
        x = X_TRUE.copy()
        x[i] += bump
        ev = cal.evaluate(qc.search_to_params(x))
        assert np.sqrt(np.mean(ev["spx_resid"]**2)) > 1e-4
        assert np.sqrt(np.mean(ev["vix_fwd_rel_resid"]**2)) > 1e-5
        assert np.sqrt(np.mean(ev["vix_resid"]**2)) > 1e-4
        assert cal._loss(x) > 1e-9

    def test_correlation_moves_only_the_spx_leg(self, cal):
        # ε does not enter the law of the vol factors, hence not VIX.
        x = X_TRUE.copy()
        x[6] += 0.25
        ev = cal.evaluate(qc.search_to_params(x))
        assert np.sqrt(np.mean(ev["spx_resid"]**2)) > 1e-3
        assert np.max(np.abs(ev["vix_fwd_rel_resid"])) < 1e-12
        assert np.max(np.abs(ev["vix_resid"])) < 1e-8

    def test_model_failures_are_penalised_not_dropped(self, cal, market, monkeypatch):
        real = q.implied_vol_surface_forward_mc

        def one_nan(*a, **k):
            iv, se = real(*a, **k)
            iv = iv.copy()
            iv[0] = np.nan
            return iv, se
        monkeypatch.setattr(qc, "implied_vol_surface_forward_mc", one_nan)
        ev = cal.evaluate(market["params"])
        assert ev["spx_resid"][0] == qc._NAN_RESIDUAL and ev["spx_n_nan"] == 1

    def test_index_leg_is_an_input_check(self, cal):
        # ξ0 reproduces the VIX indices whatever the parameters
        assert cal.xi0_index_reproduction() < 1e-10


# ── search space ↔ admissible parameters ─────────────────────────────────────

class TestSearchSpace:

    def test_mapping_is_a_bijection_with_alpha5_fixed(self):
        rng = np.random.default_rng(3)
        lo = np.array([b[0] for b in qc.SEARCH_BOUNDS])
        hi = np.array([b[1] for b in qc.SEARCH_BOUNDS])
        for _ in range(50):
            x = lo + rng.random(len(lo)) * (hi - lo)
            p = qc.search_to_params(x)
            assert p.alpha5 == 1.0
            assert q.admissibility_violations(p) == []
            np.testing.assert_allclose(qc.params_to_search(p), x, rtol=1e-10, atol=1e-12)

    def test_rescaled_polynomial_maps_to_the_same_point(self):
        p = qc.search_to_params(X_TRUE)
        scaled = q.QuinticOUParams(p.lam_x, p.lam_y, p.theta, 4 * p.alpha0, 4 * p.alpha1,
                                   4 * p.alpha3, 4.0, p.epsilon)
        np.testing.assert_allclose(qc.params_to_search(scaled), X_TRUE, rtol=1e-12)


# ── data guards (C20/C21 parity with JointCalibrator) ────────────────────────

class TestDataGuards:

    def test_vix_indices_pinned_to_spot_session(self, monkeypatch, market):
        # 06-12 complete; 06-17 (spot) has ^VIX only. The pre-C22 code took the
        # last row per ticker and mixed 06-17 ^VIX with 06-12 sub-tenors.
        vts = _vts_long({"2026-06-12": VIX_LEVELS, SPOT_DATE: {"^VIX": 30.0}})
        _install(monkeypatch, market, vts=vts)
        with pytest.raises(qc.QuinticDataError, match="VIX index tenors"):
            qc.QuinticCalibrator(SPOT_DATE, n_paths=N_PATHS, seed=SEED)
        c = qc.QuinticCalibrator.__new__(qc.QuinticCalibrator)
        c.as_of_date, c.spot_date = SPOT_DATE, SPOT_DATE
        ts = c._prepare_vix_term_structure()
        assert ts["vix_level"].tolist() == [30.0]

    def test_stale_spx_surface_is_refused(self, monkeypatch, market):
        _install(monkeypatch, market, spx_snapshot="2026-02-20")
        with pytest.raises(qc.QuinticDataError, match="SPX option snapshot 2026-02-20"):
            qc.QuinticCalibrator(SPOT_DATE, n_paths=N_PATHS, seed=SEED)
        c = qc.QuinticCalibrator(SPOT_DATE, n_paths=N_PATHS, seed=SEED, allow_stale=True)
        assert c.spx_snapshot_date == "2026-02-20"

    def test_stale_vix_options_are_refused(self, monkeypatch, market):
        _install(monkeypatch, market, vix_snapshot="2026-03-20")
        with pytest.raises(qc.QuinticDataError, match="VIX option snapshot"):
            qc.QuinticCalibrator(SPOT_DATE, n_paths=N_PATHS, seed=SEED)

    def test_too_few_spx_expiries_is_refused(self, monkeypatch, market):
        spx = market["spx"]
        keep = spx["time_to_expiry"].isin(sorted(spx["time_to_expiry"].unique())[:2])
        _install(monkeypatch, market, spx=spx[keep])
        with pytest.raises(qc.QuinticDataError, match="SPX expiries"):
            qc.QuinticCalibrator(SPOT_DATE, n_paths=N_PATHS, seed=SEED)

    def test_index_tenors_come_from_config(self, cal):
        tenors = dict(zip(cal.vix_ts["ticker"], cal.vix_ts["tenor"]))
        assert tenors["^VIX3M"] == pytest.approx(93 / 365)
        assert tenors["^VIX6M"] == pytest.approx(184 / 365)


# ── forward-variance curve ───────────────────────────────────────────────────

class TestForwardVariance:

    def test_bootstrap_reproduces_vix_indices(self):
        fv = _fwd_var()
        for t, lvl in VIX_LEVELS.items():
            assert qc._spot_vix(VIX_INDEX_TENOR_DAYS[t] / 365.0, fv) == pytest.approx(lvl, abs=1e-10)

    def test_integrated_and_breakpoints(self):
        fv = qc._PiecewiseConstVar(np.array([0.1, 0.3]), np.array([0.04, 0.09]))
        assert fv.integrated(0.2) == pytest.approx(0.1 * 0.04 + 0.1 * 0.09)
        assert fv.integrated(0.5) == pytest.approx(0.004 + 0.018 + 0.2 * 0.09)
        np.testing.assert_allclose(fv.breakpoints, [0.1])

    def test_atm_fallback_bootstraps_forward_not_term_variance(self):
        # ATM vols 15% at T = 0.1 and 25% at T = 0.5 ⇒ ξ on (0.1, 0.5] is
        # (0.25²·0.5 − 0.15²·0.1)/0.4 = 0.0725; the pre-C22 fallback used 0.0625
        # and gave a 0.5y variance-swap vol of 23.35 instead of 25.
        c = qc.QuinticCalibrator.__new__(qc.QuinticCalibrator)
        c.vix_ts = pd.DataFrame()
        c.S = 100.0
        c.spx_surface = pd.DataFrame({"time_to_expiry": [0.1, 0.1, 0.5, 0.5],
                                      "strike": [100.0, 110.0, 100.0, 90.0],
                                      "log_moneyness": [0.0, 0.095, 0.0, -0.105],
                                      "market_iv": [0.15, 0.14, 0.25, 0.27]})
        fv = c._build_fwd_var_func()
        np.testing.assert_allclose(fv.xi_nodes, [0.0225, 0.0725])
        assert qc._spot_vix(0.5, fv) == pytest.approx(25.0, abs=1e-10)

    def test_pcp_forward_ignores_a_stale_quote(self):
        F, D = 6600.0, math.exp(-0.04 * 0.5)
        K = np.arange(6400.0, 6801.0, 25.0)
        call = D * np.maximum(F - K, 0) + 50.0
        put = call - D * (F - K)
        chain = pd.concat([pd.DataFrame({"strike": K, "right": "C", "mid_price": call}),
                           pd.DataFrame({"strike": K, "right": "P", "mid_price": put})])
        stale = (chain["strike"] == 6650.0) & (chain["right"] == "C")
        chain.loc[stale, "mid_price"] = put[K == 6650.0][0]        # C − P = 0 there
        est, disp, n = qc._pcp_forward(chain, D, 5)
        assert est == pytest.approx(F, rel=1e-12)


# ── end-to-end (tiny budget) and the saved result ────────────────────────────

class TestCalibrateAndSave:

    def test_tiny_calibration_result_is_self_consistent(self, cal, tmp_path, monkeypatch):
        monkeypatch.setattr(qc, "_MC_PATHS_CHECK", N_PATHS)
        res = cal.calibrate(maxiter=0, popsize=1, polish_maxiter=1, workers=1)
        c = res["convergence"]
        assert res["n_evals"] == c["de_nfev"] + c["polish_nfev"]
        assert res["success"] == (c["de_success"] and c["polish_success"])
        # reported legs are the minimised objective's own settings
        ev = cal.evaluate(res["params"])
        assert res["loss"] == pytest.approx(cal._loss_from_eval(ev), rel=1e-12)
        mi = np.array([r["model_iv"] for r in res["spx_rows"]])
        mk = np.array([r["market_iv"] for r in res["spx_rows"]])
        resid = np.where(np.isfinite(mi), mi - mk, qc._NAN_RESIDUAL)
        assert res["leg_losses"]["spx_iv_rmse"] == pytest.approx(
            100 * math.sqrt(np.mean(resid**2)), rel=1e-12)
        assert res["params"].alpha5 == 1.0
        assert set(res["at_bound"]) == set(qc.SEARCH_NAMES)
        path = cal.save(tmp_path / "q.pkl")
        with open(path, "rb") as f:
            again = pickle.load(f)
        assert again["leg_losses"] == res["leg_losses"]
        assert again["provenance"]["spx_snapshot_date"] == SPOT_DATE
